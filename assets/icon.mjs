// Generates the shared translator logo from the faceted FastTools snake.
// Embed the snake so the SVG works as an <img> without loading another file.
// Run `npm run icons` after changing the artwork.
import { readFile, writeFile } from 'node:fs/promises';

const dir = new URL('./', import.meta.url);
const facetedSnake = `data:image/png;base64,${(await readFile(new URL('aspid-snake.png', dir))).toString('base64')}`;

const GLYPH = '#e8f5ec';
const GLYPH_OUTLINE = '#0c1410';

// "文" and "A", drawn around (60, 30.25) and (35, 63).
const WEN = `<path d="M60 16.5 V19.5"/>
      <path d="M49 24 H71"/>
      <path d="M66.5 27 Q62.5 37.5 49 44"/>
      <path d="M53.5 27 Q57.5 37.5 71 44"/>`;
const A = `<path d="M26 74 L35 52 L44 74"/>
      <path d="M29 67 H41"/>`;

const frontGlyphs = (color, width) => `<g fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">
    <g transform="translate(40 40.5) scale(0.88) translate(-60 -30.25)">
      ${WEN}
    </g>
    <g transform="translate(61 64) scale(0.88) translate(-35 -63)">
      ${A}
    </g>
  </g>`;

const logo = `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">
  <!-- Generated by assets/icon.mjs, do not edit by hand. -->
  <defs>
    <image id="faceted-snake" width="96" height="96" href="${facetedSnake}"/>
    <filter id="glyph-shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="1.4" stdDeviation="1.25" flood-color="#06140a" flood-opacity="0.65"/>
    </filter>
    <!-- The inner edges of the coils hide the end of 文 and the right foot of A. -->
    <clipPath id="front-coils">
      <rect x="27" y="40" width="28" height="19"/>
      <rect x="62" y="63" width="20" height="21"/>
    </clipPath>
  </defs>
  <use href="#faceted-snake"/>
  <g filter="url(#glyph-shadow)">
    ${frontGlyphs(GLYPH_OUTLINE, 9.5)}
    ${frontGlyphs(GLYPH, 6.5)}
  </g>
  <use href="#faceted-snake" clip-path="url(#front-coils)"/>
</svg>
`;

await writeFile(new URL('banner-logo.svg', dir), logo);
